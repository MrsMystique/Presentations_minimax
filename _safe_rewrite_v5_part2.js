// ============ ПРАВКА 3: Слайд 14 → 14a + 14b ============
console.log('\n--- ПРАВКА 3: Слайд 14 → 14a + 14b ---');
const slide14Start = '### Слайд 14.';
const slide14End = '### Слайд 15.';
const idx14 = md.indexOf(slide14Start);
const idx14End = md.indexOf(slide14End, idx14);

const slide14Content = md.substring(idx14, idx14End);
