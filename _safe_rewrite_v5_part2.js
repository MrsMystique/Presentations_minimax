// ============ ПРАВКА 9: Слайд 13.2 — добавить «8% = 40 г» ============
console.log('\n--- ПРАВКА 9: Слайд 13.2 — 8% = 40 г ---');
const algorithmIdx = md.indexOf('Алгоритм «3 шага»:');
if (algorithmIdx > 0) {
  const explanation = `\n**Что значит «8% соли»?** Это 8% от общей массы раствора. Если раствор весит 500 г, то соли в нём \\(500 \\cdot 0{,}08 = 40\\) г. Остальные 92% — это вода (или растворитель): \\(500 \\cdot 0{,}92 = 460\\) г. Сумма: 40 г + 460 г = 500 г — все компоненты складываются обратно в общую массу.\n\n`;
  const insertPos = md.indexOf('\n\n', algorithmIdx) + 1;
  md = md.substring(0, insertPos) + explanation + md.substring(insertPos);
  console.log('✓ Слайд 13.2: добавлено пояснение про 8% соли');
  count++;
}

// ============ ПРАВКА 10: Слайд 22.9 — разбить шаги 5-7 ============
console.log('\n--- ПРАВКА 10: Слайд 22.9 — разбить шаги 5-7 ---');
const oldSteps56 = `5. Перенесём все члены с \\(A\\) влево, с \\(B\\) — вправо: \\(0{,}03A - 0{,}45B = 0\\).\n6. Поделим обе части на \\(B\\) и получим: \\(\\frac{0{,}03A}{B} = \\frac{0{,}45B}{B}\\), или \\(\\frac{0{,}03A}{B} = 0{,}45\\).`;

