// Найдём первый слайд (после сдвига это Слайд 3 — Пропорция)
const firstSlideMarker = '### Слайд 3. Пропорция: равенство двух отношений';
const firstSlidePos = content.indexOf(firstSlideMarker);

if (firstSlidePos >= 0) {
  content = content.substring(0, firstSlidePos) + titulnikBlock + content.substring(firstSlidePos);
  console.log('✓ Титульник и Содержание вставлены перед Слайдом 3');
} else {
  console.log('✗ Не найден Слайд 3 для вставки');
}

fs.writeFileSync(filePath, content, 'utf8');

// Проверим конфликты
const m = content.match(/^### Слайд [^\n]*$/gm);
const conflicts = {};
m.forEach(x => {
  const num = x.match(/### Слайд ([0-9.]+)/)[1];
  conflicts[num] = (conflicts[num] || 0) + 1;
});
let hasConflict = false;
Object.keys(conflicts).forEach(k => {
  if (conflicts[k] > 1) {
    console.log('CONFLICT: Слайд ' + k + ' x' + conflicts[k]);
    hasConflict = true;
  }
});
if (!hasConflict) console.log('\n=== NO CONFLICTS, file saved ===');
console.log('Total slides: ' + m.length);
