const titulnikClean = `### Слайд 3. Пропорция: равенство двух отношений

**Почему это важно?**`;
if (c.indexOf(titulnikOnS3) >= 0) {
  c = c.replace(titulnikOnS3, titulnikClean);
  a++;
  console.log('✓ Удалён дубль titulnik-procenty со Слайда 3');
} else {
  console.log('  (titulnik уже удалён со Слайда 3)');
}

console.log('Applied: ' + a);
fs.writeFileSync(p, c, 'utf8');
