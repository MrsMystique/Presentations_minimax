// Финальные правки: убрать эмодзи (🚨 ⚠️ 🪞) + добавить «Как думать» в Слайды 12, 24.4, 24.8
const fs = require('fs');
const p = 'Чистовые слайды v3.3 — Проценты, пропорции, масштаб.md';
let c = fs.readFileSync(p, 'utf8');
let a = 0;

// === 1. Удалить все дешёвые эмодзи ===
const emojiList = ['🚨', '⚠️', '🪞', '💡', '🔍', '🛠️', '🎯', '🔑', '🧱', '🔎', '📐', '🎨', '🛑'];
for (const e of emojiList) {
  const reg = new RegExp(e + '\\s*', 'g');
  const before = c;
  c = c.replace(reg, '');
  const count = (before.match(new RegExp(e, 'g')) || []).length;
  if (count > 0) {
    a++;
    console.log('✓ Removed ' + count + ' of ' + e);
  }
}

// === 2. Слайд 12 — добавить «Как думать» ===
// После убирания эмодзи паттерн: "> Возможная ловушка:"
const slide12EndOld = '> Возможная ловушка:';
const slide12EndNew = `**Как думать при новой задаче «найти процент от числа»:**

1. **Найди целое** (то, от чего считаем) и **процент**.
2. **Запиши формулу:** часть = целое × (процент / 100).
3. **Подставь и считай.** Если процент дробный (12,5%) — умножай на десятичную дробь (0,125).

` + slide12EndOld;
if (c.indexOf('### Слайд 12.') >= 0) {
  const idx12 = c.indexOf('### Слайд 12.');
  const idx13 = c.indexOf('### Слайд 13.');
  if (idx13 > 0) {
    const slide12 = c.substring(idx12, idx13);
    if (slide12.indexOf('Найди целое (то, от чего считаем)') < 0) {
      const newSlide12 = slide12.replace(slide12EndOld, slide12EndNew);
      if (newSlide12 !== slide12) {
        c = c.substring(0, idx12) + newSlide12 + c.substring(idx13);
        a++;
        console.log('✓ Слайд 12: Как думать');
      }
    }
  }
}

// === 3. Слайд 24.4 — добавить «Как думать» ===
const slide244EndOld = '> Возможная ловушка: ученик думает';
const slide244EndNew = slide244EndOld + `

**Как думать при новой задаче на зависимость:**

1. **Пойми смысл задачи:** что происходит с одной величиной, когда другая растёт? Больше → больше (прямая) или больше → меньше (обратная)?
2. **Запиши пропорцию** по выбранному типу. Прямая: \\(A_1/B_1 = A_2/B_2\\). Обратная: \\(A_1/B_2 = A_2/B_1\\) (одна колонка перевёрнута).
3. **Реши через закон наискосок.**`;
if (c.indexOf(slide244EndOld) >= 0 && c.indexOf('Пойми смысл задачи') < 0) {
  c = c.replace(slide244EndOld, slide244EndNew);
  a++;
  console.log('✓ Слайд 24.4: Как думать');
}

// === 4. Слайд 24.8 — добавить «Как думать» ===
const slide248EndOld = '> Возможная ловушка: ученик забывает';
const slide248EndNew = slide248EndOld + `

**Как думать при новой задаче на переливание:**

1. **Определи направление** переливания: из какого сосуда в какой.
2. **Запиши, сколько процентов** ушло из одного сосуда и сколько пришло в другой.
3. **Запиши равенство** массы или объёма в каждом сосуде после переливания.`;
if (c.indexOf(slide248EndOld) >= 0 && c.indexOf('Определи направление') < 0) {
  c = c.replace(slide248EndOld, slide248EndNew);
  a++;
  console.log('✓ Слайд 24.8: Как думать');
}

// === 5. Исправить ссылки на старые номера слайдов ===
const refFixes = [
  ['простой процент (Слайд 12)', 'простой процент (Слайд 14)'],
  ['сложный процент (Слайд 13)', 'сложный процент (Слайд 16)'],
  ['Формула сложных процентов (Слайд 14):', 'Формула сложных процентов (Слайд 17):'],
  ['Простой процент часто путают ... это сложный процент (Слайд 13).',
   'Простой процент часто путают ... это сложный процент (Слайд 16).'],
];
for (const [from, to] of refFixes) {
  // Ищем по куску, чтобы не ломать экранирование
  const fromShort = from.split(' ')[0];
  if (c.indexOf(fromShort) >= 0 && c.indexOf(from) >= 0) {
    c = c.replace(from, to);
    a++;
    console.log('✓ Ref: ' + from.substring(0, 40) + ' → ' + to.substring(0, 40));
  }
}

// Слайд 14 ссылка в Слайде 14: «Слайд 13» — ручной патч
if (c.indexOf('там процент применяется к НОВОЙ сумме — это сложный процент (Слайд 13).') >= 0) {
  c = c.replace(
    'там процент применяется к НОВОЙ сумме — это сложный процент (Слайд 13).',
    'там процент применяется к НОВОЙ сумме — это сложный процент (Слайд 16).'
  );
  a++;
  console.log('✓ Слайд 14: ссылка Слайд 13 → Слайд 16');
}

console.log('\nApplied: ' + a);
fs.writeFileSync(p, c, 'utf8');

// Проверим итог
const slides = c.match(/^### Слайд [^\n]*$/gm);
console.log('Total slides: ' + slides.length);

// Оставшиеся эмодзи
const remaining = c.match(/[\u{1F300}-\u{1FAFF}]|[\u{2600}-\u{27BF}]/gu);
if (remaining) {
  const counts = {};
  remaining.forEach(e => counts[e] = (counts[e] || 0) + 1);
  console.log('Remaining emoji:');
  Object.keys(counts).forEach(k => console.log('  ' + k + ' x' + counts[k]));
} else {
  console.log('No emoji remaining');
}
