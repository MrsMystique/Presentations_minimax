// Фикс Слайда 17 v2: построчные замены
const fs = require('fs');
const p = 'Чистовые слайды v3.3 — Проценты, пропорции, масштаб.md';
let c = fs.readFileSync(p, 'utf8');

const fixes = [
  // Условие
  ['В банк положили 1000 руб под \\(10\\%\\) годовых. Сколько денег будет на счёте через 3 года',
   'В банк положили 50000 руб под \\(8\\%\\) годовых. Сколько денег будет на счёте через 3 года'],
  // Интуиция: k = 1,1 → 1,08
  ['берём текущую сумму и умножаем на \\(k = 1{,}1\\)',
   'берём текущую сумму и умножаем на \\(k = 1{,}08\\)'],
  // Год 1
  ['**Год 1:** \\(1000 \\cdot 1{,}1 = 1100\\).',
   '**Год 1:** \\(50000 \\cdot 1{,}08 = 54000\\).'],
  // Год 2
  ['**Год 2:** \\(1100 \\cdot 1{,}1 = 1210\\).',
   '**Год 2:** \\(54000 \\cdot 1{,}08 = 58320\\).'],
  // Год 3
  ['**Год 3:** \\(1210 \\cdot 1{,}1 = 1331\\).',
   '**Год 3:** \\(58320 \\cdot 1{,}08 = 62985{,}6\\).'],
  // Формула
  ['\\(S_3 = 1000 \\cdot (1{,}1)^3 = 1000 \\cdot 1{,}331 = 1331\\).',
   '\\(S_3 = 50000 \\cdot (1{,}08)^3 = 50000 \\cdot 1{,}259712 = 62985{,}6\\).'],
  // Ответ
  ['**Ответ:** 1331 руб.',
   '**Ответ:** 62985 руб 60 коп. (или 62985,6 руб).'],
];

let applied = 0;
for (const [from, to] of fixes) {
  if (c.indexOf(from) >= 0) {
    c = c.replace(from, to);
    applied++;
    console.log('✓ ' + from.substring(0, 60));
  } else {
    console.log('✗ NOT FOUND: ' + from.substring(0, 60));
  }
}
console.log('Applied: ' + applied + '/' + fixes.length);

fs.writeFileSync(p, c, 'utf8');
console.log('=== DONE ===');
