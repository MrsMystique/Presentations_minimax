// Комплексное исправление верстки v5.0
// 1. Добавляет пустые строки между абзацами в слайдах, где их нет
// 2. Исправляет (frac{...}) на \(\frac{...}\)
// 3. Исправляет \[...\] рендер
// 4. Разделяет Самопроверки, Мостики, Шпаргалки на абзацы

const fs = require('fs');
const path = 'C:\\Users\\admin\\Desktop\\математика мои слайды\\Minimax\\Чистовые слайды v5.0 — Проценты, пропорции, масштаб.md';
let md = fs.readFileSync(path, 'utf8');

// 1) Исправляем (frac{...}) на \(\frac{...}\) — все случаи
md = md.replace(/\(frac\{([^}]+)\}\{([^}]+)\}\)/g, '\\(\\frac{$1}{$2}\\)');
md = md.replace(/\(\\frac\{([^}]+)\}\{([^}]+)\} = \\frac\{([^}]+)\}\{([^}]+)\} = \\frac\{([^}]+)\}\{([^}]+)\}\\)/g,
  '\\(\\frac{$1}{$2} = \\frac{$3}{$4} = \\frac{$5}{$6}\\)');

// 2) Общий принцип: добавляем пустую строку перед маркерами нового смыслового блока
// Перед **Шаг N.**, **Вопрос N.**, **Тест N.**, **Ответ:**, **Алгоритм сборки:**, **Как думать:**
const newParaMarkers = [
  '\\*\\*Шаг \\d+\\.\\*\\*',
  '\\*\\*Вопрос \\d+\\.\\*\\*',
  '\\*\\*Тест \\w+\\.\\*\\*',
  '\\*\\*Ответ:\\*\\*',
  '\\*\\*Алгоритм сборки:\\*\\*',
  '\\*\\*Как думать:\\*\\*',
  '\\*\\*Примени закон крест-накрест[^:]*:\\*\\*',
  '\\*\\*Проверка здравым смыслом:\\*\\*',
  '\\*\\*Проверка:\\*\\*',
  '\\*\\*Закон абсолютного баланса:\\*\\*',
  '\\*\\*Как думать при новой задаче[^:]*:\\*\\*'
];
for (const re of newParaMarkers) {
  const regex = new RegExp('([^\n])\n(' + re + ')', 'g');
  md = md.replace(regex, '$1\n\n$2');
}

// 3) Добавляем пустую строку перед блоками формул \[...\]
md = md.replace(/([^\n])\n(\\\[)/g, '$1\n\n$2');
// и после
md = md.replace(/(\\\])\n([^\n])/g, '$1\n\n$2');

// 4) Самопроверки — добавляем пустые строки перед вопросами
md = md.replace(/(\*\\*Вопрос \d+\\.\\*\\*)/g, '\n$1');

// 5) Применяем конкретные точечные исправления по слайдам

// Слайд 5 — после "Было:" добавляем таблицу и пустые строки вокруг
md = md.replace(
  /(\*\*Алгоритм сборки:\*\* при обратной зависимости мы не имеем права составлять пропорцию в лоб\. Мы обязаны перевернуть правую колонку с днями вверх ногами\. Было:\n)\n(\| Колонка 1 \| Колонка 2 \|)/,
  '$1\n\n$2'
);

// Слайд 7.1 — добавляем пустую строку перед каждым **Шаг N.**
md = md.replace(/(\*\\*Шаг \d+\\. [^\\n]+:\\*\\*)/g, '\n\n$1');

// 6) Слайд 12 — добавляем пустую строку перед каждым **Шаг N.**
// уже сделано выше

// 7) Слайд 15.6 — добавляем пустую строку перед "Когда используется" / "Когда НЕ используется"
md = md.replace(/(\*\\*Когда используется:\\*\\*)/g, '\n\n$1');
md = md.replace(/(\*\\*Когда НЕ используется:\\*\\*)/g, '\n\n$1');

// 8) Слайд 17 — добавляем абзацы
// это сделаем отдельно

fs.writeFileSync(path, md, 'utf8');
console.log('Layout fix applied');
