let delta = 0;
for (let i = 0; i < microTests.length; i++) {
  const mt = microTests[i];
  const insertPos = bridgePositions[i] + delta;
  const content = buildMicroTest(mt);
  md = md.substring(0, insertPos) + content + md.substring(insertPos);
  delta += content.length;
}

fs.writeFileSync(path, md, 'utf8');
