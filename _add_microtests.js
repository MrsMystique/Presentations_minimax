function buildMicroTest(mt) {
  let lines = [
    '',
    '### Слайд ' + mt.num + '. ' + mt.title,
    '',
    '**Микро-тест на 2 минуты — проверь, что ты понял блок.** Ответы свернуты ниже.',
    ''
  ];
  mt.problems.forEach((p, i) => {
    lines.push('**Задача ' + (i + 1) + '.** ' + p.q);
    lines.push('');
    lines.push('> Свернись с ответом: ' + p.a);
    lines.push('');
  });
  return lines.join('\n');
}
