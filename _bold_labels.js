// Добавляет **жирное** выделение для стандартных меток в начале абзацев
const fs = require('fs');
const path = 'C:\\Users\\admin\\Desktop\\математика мои слайды\\Minimax\\Чистовые слайды v5.0 — Проценты, пропорции, масштаб.md';
let md = fs.readFileSync(path, 'utf8');

// Метки, которые должны быть выделены жирным в начале абзаца
// Ищем паттерн "> Метка:" или "> Метка —" (внутри blockquote)
const labels = [
  'Лайфхак',
  'Практический приём',
  'Возможная ловушка',
  'Жёсткое ограничение',
  'Паспорт темы',
  'Закон-триггер',
  'Совет ученикам',
  'Твой первый кирпич урока готов',
  'Главное открытие',
  'Три главных слова-подсказки',
  'Как распознать ЦЕЛОЕ',
  'Закон суммы долей',
  'Закон абсолютного баланса говорит',
  'Когда используется',
  'Когда НЕ используется',
  'Закон 6 нулей',
  'Алгоритм «3 шага»',
  'Правило проверки',
  'Проверка здравым смыслом',
  'Проверка'
];

let changed = 0;
for (const label of labels) {
  // Ищем вариант: "> Метка:" или "> Метка —" — если уже не в **...**
  const re = new RegExp('(> )(' + label + ')([:\\s—])', 'g');
  md = md.replace(re, (match, prefix, lbl, sep) => {
    // Проверяем что метка не уже жирная
    if (match.includes('**' + lbl + '**')) return match;
    changed++;
    return prefix + '**' + lbl + '**' + sep;
  });
}

fs.writeFileSync(path, md, 'utf8');
console.log('Выделено жирным меток:', changed);
