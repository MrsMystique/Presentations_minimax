// Главный rewrite v5.0 — Правки 1, 3, 5, 6, 7 + замечания экспертов
const fs = require('fs');
const path = 'C:\\Users\\admin\\Desktop\\математика мои слайды\\Minimax\\Чистовые слайды v5.0 — Проценты, пропорции, масштаб.md';
let md = fs.readFileSync(path, 'utf8');

let totalChanges = 0;

function replace(oldStr, newStr, label) {
  if (md.includes(oldStr)) {
    md = md.replace(oldStr, newStr);
    console.log(`✓ ${label}`);
    return 1;
  } else {
    console.log(`✗ ${label} — не найдено`);
    return 0;
  }
}

// ============ ПРАВКА 5: Слайд 21 — переставить в начало Блока 7 ============
console.log('\n=== ПРАВКА 5: Слайд 21 → начало Блока 7 ===');
const slide21Start = '### Слайд 21. Зачем тебе всё это: мотивация перед экзаменом';
const slide21End = '### Слайд 16.5. Мини-тест: шпаргалки в деле';
const idx21 = md.indexOf(slide21Start);
const idx21End = md.indexOf(slide21End);
if (idx21 >= 0 && idx21End >= 0) {
  const slide21Block = md.substring(idx21, idx21End);
  console.log(`Слайд 21 блок: ${slide21Block.length} символов`);

  // Найдём начало Блока 7 (после Мостик 6)
  const block7Start = md.indexOf('## Блок 7. Сборник формул');
  if (block7Start >= 0) {
    // Найдём конец вступительной строки Блока 7 (после пустой строки после заголовка)
    const block7HeadingEnd = md.indexOf('\n', block7Start);
    const block7FirstEmpty = md.indexOf('\n\n', block7HeadingEnd);
    if (block7FirstEmpty >= 0) {
      const insertPos = block7FirstEmpty + 1; // после пустой строки
      // Удаляем старый Слайд 21
      md = md.substring(0, idx21) + md.substring(idx21End);
      // Корректируем insertPos (сдвиг из-за удаления)
      const newInsertPos = insertPos - (idx21End - idx21);
      // Вставляем Слайд 21 в начало Блока 7
      const newSlide21 = slide21Block + '\n\n';
      md = md.substring(0, newInsertPos) + newSlide21 + md.substring(newInsertPos);
      console.log('✓ Слайд 21 переставлен в начало Блока 7');
      totalChanges++;
    }
  }
}

