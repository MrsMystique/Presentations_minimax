// Шаг 3: переименовать Слайд 2 (Пропорция) → Слайд 3 + переместить Слайд 1 и 2 перед Блоком 1
const fs = require('fs');
const path = require('path');

const filePath = path.join(
  'C:\\Users\\admin\\Desktop\\математика мои слайды\\Minimax',
  'Чистовые слайды v3.3 — Проценты, пропорции, масштаб.md'
);

let content = fs.readFileSync(filePath, 'utf8');

// 1. Переименовать Слайд 2 (Пропорция) → Слайд 3 (Пропорция)
const oldS2Prop = '### Слайд 2. Пропорция: равенство двух отношений';
const newS3Prop = '### Слайд 3. Пропорция: равенство двух отношений';

if (content.indexOf(oldS2Prop) >= 0) {
  content = content.replace(oldS2Prop, newS3Prop);
  console.log('Слайд 2 (Пропорция) → Слайд 3 (Пропорция)');
} else {
  console.log('NOT FOUND: oldS2Prop');
}

// 2. Также обновить ссылку в содержании (Слайд 2 → Слайд 3 для Пропорции)
content = content.replace('- Слайд 2: Пропорция: равенство двух отношений', '- Слайд 3: Пропорция: равенство двух отношений');
content = content.replace('- Слайд 3: Как решать задачу через пропорцию (алгоритм 3 шага)', '- Слайд 4: Как решать задачу через пропорцию (алгоритм 3 шага)');
content = content.replace('- Слайд 4: Свойство пропорции (закон крест-накрест)', '- Слайд 5: Свойство пропорции (закон крест-накрест)');
content = content.replace('**Блок 1. Пропорция** (Слайды 2-4)', '**Блок 1. Пропорция** (Слайды 3-5)');

// Аналогично для всех блоков в Содержании — сдвиг +1
// После сдвига Слайдов 1, 2, 3, 4, 5 → 2, 3, 4, 5, 6 — НЕТ, я переименовал только 2→3 (Пропорция)
// Другие сдвиги уже сделаны через renames. Сейчас:
// - Бывший Слайд 1 → Слайд 2 (Пропорция) → Слайд 3 (только что)
// - Бывший Слайд 2 (Как решать) → Слайд 3 (Как решать) → теперь Слайд 4?
// - Бывший Слайд 3 (Свойство) → Слайд 4 (Свойство) → Слайд 5?

// Проверю текущее состояние слайдов 3-5 и поправлю.
const lines = content.split('\n');
lines.forEach((line, i) => {
  if (line.startsWith('### Слайд 3. Как решать') ||
      line.startsWith('### Слайд 4. Свойство') ||
      line.startsWith('### Слайд 5. Прямая')) {
    console.log('  Found: ' + line.substring(0, 70));
  }
});

console.log('\nSaving file...');
fs.writeFileSync(filePath, content, 'utf8');