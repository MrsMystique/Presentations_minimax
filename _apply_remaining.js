// Доделка: переименование 14.1/14.2 в 15.1/15.2 + пропущенные правки
const fs = require('fs');
const p = 'Чистовые слайды v3.3 — Проценты, пропорции, масштаб.md';
let c = fs.readFileSync(p, 'utf8');

const fixes = [
  // 14.1 → 15.1
  ['### Слайд 14.1. Скрипт самопроверки Блока 5',
   '### Слайд 15.1. Скрипт самопроверки Блока 5'],
  // 14.2 → 15.2
  ['### Слайд 14.2. Задачи на смеси и сплавы (растворы)',
   '### Слайд 15.2. Задачи на смеси и сплавы (растворы)'],
  // Слайд 23: добавить картинку шпоры
  ['### Слайд 23. Зачем тебе всё это: мотивация перед экзаменом\n\nПроценты,',
   '### Слайд 23. Зачем тебе всё это: мотивация перед экзаменом\n\n![Можно, это шпора! Хитрый граф подглядывает — но легенда разрешает использовать шпаргалки как инструмент](assets/shpory-mozhno.png)\n\nПроценты,'],
  // Слайд 15.2: добавить ловушку соль/вода
  ['![Смеси и сплавы: закон суммы долей — два раствора 10% и 20% сливаются, формула m₁ + m₂ = const](assets/smesi-splavy.png)\n\n**Что прячется:**',
   '![Смеси и сплавы: закон суммы долей — два раствора 10% и 20% сливаются, формула m₁ + m₂ = const](assets/smesi-splavy.png)\n\n> **Возможная ловушка:** не путай «процент соли» с «процентом воды». В растворе соли \\(8\\%\\) означает \\(8\\%\\) массы — это соль. Остальные \\(92\\%\\) — вода. Если в задаче спрашивают «процент воды», ответ будет \\(92\\%\\), а не \\(8\\%\\). Всегда смотри, ЧТО именно в процентах: соль, вода, кислота, спирт, жир, примесь.\n\n**Что прячется:**'],
  // Убрать оставшиеся эмодзи
  ['> 🛠 **Практический приём:**',
   '> **Практический приём:**'],
  ['**🔑 Правило:**',
   '**Правило:**'],
  ['🎯 **Поздравляю:**',
   '**Поздравляю:**'],
  ['🎯 Поздравляю:',
   '**Поздравляю:**'],
  ['**🪞 Интуиция',
   '**Интуиция'],
  ['> 🔎 **Откуда',
   '> **Откуда'],
];

let applied = 0;
for (const [from, to] of fixes) {
  if (c.indexOf(from) >= 0) {
    c = c.replace(from, to);
    applied++;
    console.log('✓ ' + from.substring(0, 50));
  } else {
    console.log('  not found: ' + from.substring(0, 50));
  }
}

// Также убираем все оставшиеся дешёвые эмодзи 💡 🚨 ⚠️ 🔍 🛠 🎯 🔑 🧱 🪞 🔎
const extraEmojiReplacements = [
  ['💡', ''],
  ['🚨', ''],
  ['⚠️', ''],
  ['🔍', ''],
  ['🛠️', ''],
  ['🛠', ''],
  ['🎯', ''],
  ['🔑', ''],
  ['🧱', ''],
  ['🪞', ''],
  ['🔎', ''],
];
for (const [emoji, replacement] of extraEmojiReplacements) {
  // Заменяем эмодзи + пробел (если есть) на пустую строку
  const reg = new RegExp(emoji + '\\s*', 'g');
  const before = c;
  c = c.replace(reg, replacement);
  if (before !== c) {
    const count = (before.match(new RegExp(emoji, 'g')) || []).length;
    console.log('✓ Removed ' + count + ' occurrences of ' + emoji);
    applied++;
  }
}

console.log('Total applied: ' + applied);
fs.writeFileSync(p, c, 'utf8');
