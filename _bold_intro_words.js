// Выделяет жирным вводные слова в красных блоках (ловушка)
const fs = require('fs');
const path = 'C:\\Users\\admin\\Desktop\\математика мои слайды\\Minimax\\Чистовые слайды v5.0 — Проценты, пропорции, масштаб.md';
let md = fs.readFileSync(path, 'utf8');

// Паттерны вводных слов, которые нужно выделить жирным
// Ищем: "> Возможная ловушка: <intro>."
const introPatterns = [
  'ученик забывает',
  'ученик складывает',
  'ученик считает',
  'ученик делит',
  'ученик путает',
  'ученик переворачивает',
  'ученик думает',
  'ученик не',
  'ученик применяет',
  'ученик переводит',
  'ученик умножает',
  'ученик находит',
  'ученик ошибается'
];

let count = 0;
for (const intro of introPatterns) {
  // Ищем "> Возможная ловушка: <intro>..." — выделяем жирным до первой точки или запятой
  const re = new RegExp('(ловушка:\\s+)(' + intro + ')([^.]*?\\.)', 'g');
  md = md.replace(re, (match, prefix, verb, rest) => {
    if (match.includes('**' + verb + '**')) return match; // уже выделено
    count++;
    return prefix + '**' + verb + '**' + rest;
  });
}

// Также выделяем вводные слова в советах ученикам
const advicePatterns = [
  'Всегда проверяй',
  'Всегда помни',
  'Помни:',
  'Правило:',
  'Важно:'
];

fs.writeFileSync(path, md, 'utf8');
console.log('Выделено жирным вводных слов:', count);
