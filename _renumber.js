// Восстановление нумерации v3.3 (1=Титульник, 2=TOC, 24.x=Ловушки)
const fs = require('fs');
const mdPath = 'C:\\Users\\admin\\Desktop\\математика мои слайды\\Minimax\\Чистовые слайды v3.3 — Проценты, пропорции, масштаб.md';
let md = fs.readFileSync(mdPath, 'utf8');

// Заменяем Слайд 1 (Пропорция) → Титульник
md = md.replace(
  /### Слайд 1\. Пропорция: равенство двух отношений[\s\S]*?(?=### Слайд 2\.)/,
  `### Слайд 1. Партия №3 — Проценты, пропорции, масштаб

Партия №3 из цикла «Математика для абсолютного нуля». Здесь собраны пропорция, прямая и обратная зависимость, масштаб, проценты всех типов, сложный процент и десять разборов реальных ловушек. После этой партии задачи на проценты — твоя территория.

### Слайд 2. Содержание

Полная карта партии — в боковой навигации слева. Здесь дублировать её текстом нет смысла: она занимает много места и ничего не добавляет к навигации. Открывай разделы по мере прохождения.

`
);

// Сдвигаем нумерацию: 3→4, 4→5, ..., 22→24, 22.1→24.1, ..., 22.9→24.9
// Делаем в обратном порядке, чтобы не конфликтовать
const renumber = (oldNum, newNum) => {
  const re = new RegExp('### Слайд ' + oldNum.replace('.', '\\.') + '\\.', 'g');
  md = md.replace(re, '### Слайд ' + newNum + '.');
};

for (let i = 22; i >= 3; i--) {
  renumber(String(i), String(i + 1));
}
// Ловушки
for (let i = 9; i >= 1; i--) {
  renumber('22.' + i, '24.' + i);
}

// Исправляем \nbsp
md = md.replace(/\\nbsp/g, '\\,');

// Подчищаем пустые строки
md = md.replace(/\n{3,}/g, '\n\n');

fs.writeFileSync(mdPath, md, 'utf8');

// Добавляем осознанные INLINE-стикеры
const placements = {
  'Слайд 4. Пропорция: равенство двух отношений': ['balans.png'],
  'Слайд 5. Как решать задачу через пропорцию': ['kak-dumat.png'],
  'Слайд 7. Обратная зависимость: противофаза': ['kak-naschet-uravneniya.png'],
  'Слайд 9. Перевод единиц: метрический мост': ['layfkhak.png'],
  'Слайд 10. Что такое процент: сотая часть целого': ['vnimatelno.png'],
  'Слайд 12. Тип 1': ['primer.png'],
  'Слайд 13. Тип 2': ['primer.png'],
  'Слайд 13.2. Задачи на смеси': ['primer.png'],
  'Слайд 14. Что такое сложный процент': ['klan-v-dele.png'],
  'Слайд 15. Задача на сложный процент': ['primer.png'],
  'Слайд 21. Зачем тебе всё это': ['ty-smozhesh.png']
};

const lines = md.split(/\r?\n/);
const out = [];
for (let i = 0; i < lines.length; i++) {
  out.push(lines[i]);
  for (const key of Object.keys(placements)) {
    if (lines[i].includes('### ' + key)) {
      const block = placements[key].map(f => `<!--INLINE:${f}-->`).join('\n');
      out.push('');
      out.push(block);
      break;
    }
  }
}
fs.writeFileSync(mdPath, out.join('\n'), 'utf8');
console.log('Готово. Слайдов и мостиков должно быть ~40.');
