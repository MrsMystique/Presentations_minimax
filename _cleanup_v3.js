// Финальная очистка: shpory + убрать эмодзи + «Как думать» блоки
const fs = require('fs');
const p = 'Чистовые слайды v3.3 — Проценты, пропорции, масштаб.md';
let c = fs.readFileSync(p, 'utf8');
let a = 0;

// 1. Слайд 23: добавить shpory-mozhno.png
const slide23Old = '### Слайд 23. Зачем тебе всё это: мотивация перед экзаменом\n\nПроценты,';
const slide23New = '### Слайд 23. Зачем тебе всё это: мотивация перед экзаменом\n\n![Можно, это шпора! Хитрый граф подглядывает — но легенда разрешает использовать шпаргалки как инструмент](assets/shpory-mozhno.png)\n\nПроценты,';
if (c.indexOf(slide23Old) >= 0 && c.indexOf('shpory-mozhno.png') < 0) {
  c = c.replace(slide23Old, slide23New);
  a++;
  console.log('✓ Слайд 23: shpory-mozhno.png добавлена');
}

// 2. Убрать все дешёвые эмодзи
const emojis = ['🚨', '⚠️', '🪞', '💡', '🔍', '🛠️', '🎯', '🔑', '🧱', '🔎', '📐', '🎨', '🛑'];
for (const e of emojis) {
  const reg = new RegExp(e + '\\s*', 'g');
  const before = c;
  c = c.replace(reg, '');
  const count = (before.match(new RegExp(e, 'g')) || []).length;
  if (count > 0) {
    a++;
    console.log('✓ Removed ' + count + ' of ' + e);
  }
}

// 3. «Как думать» в Слайде 12 (после ловушки)
// Найдём конец Слайда 12
const idx12 = c.indexOf('### Слайд 12.');
const idx13 = c.indexOf('### Слайд 13.');
if (idx12 >= 0 && idx13 > 0) {
  const slide12 = c.substring(idx12, idx13);
  if (slide12.indexOf('Найди целое (то, от чего считаем)') < 0) {
    const newSlide12 = slide12.replace(
      '> Возможная ловушка:',
      `**Как думать при новой задаче «найти процент от числа»:**

1. **Найди целое** (то, от чего считаем) и **процент**.
2. **Запиши формулу:** часть = целое × (процент / 100).
3. **Подставь и считай.** Если процент дробный (12,5%) — умножай на десятичную дробь (0,125).

` + '> Возможная ловушка:'
    );
    if (newSlide12 !== slide12) {
      c = c.substring(0, idx12) + newSlide12 + c.substring(idx13);
      a++;
      console.log('✓ Слайд 12: Как думать');
    }
  }
}

// 4. «Как думать» в Слайде 24.4 (после ловушки)
const slide244Old = '> Возможная ловушка: ученик думает «меньше рабочих → больше дней';
const slide244New = slide244Old + `

**Как думать при новой задаче на зависимость:**

1. **Пойми смысл задачи:** что происходит с одной величиной, когда другая растёт? Больше → больше (прямая) или больше → меньше (обратная)?
2. **Запиши пропорцию** по выбранному типу. Прямая: \\(A_1/B_1 = A_2/B_2\\). Обратная: \\(A_1/B_2 = A_2/B_1\\) (одна колонка перевёрнута).
3. **Реши через закон наискосок.**`;
if (c.indexOf(slide244Old) >= 0 && c.indexOf('Пойми смысл задачи') < 0) {
  c = c.replace(slide244Old, slide244New);
  a++;
  console.log('✓ Слайд 24.4: Как думать');
}

// 5. «Как думать» в Слайде 24.8
const slide248Old = '> Возможная ловушка: ученик забывает';
const slide248New = slide248Old + `

**Как думать при новой задаче на переливание:**

1. **Определи направление** переливания: из какого сосуда в какой.
2. **Запиши, сколько процентов** ушло из одного сосуда и сколько пришло в другой.
3. **Запиши равенство** массы или объёма в каждом сосуде после переливания.`;
if (c.indexOf(slide248Old) >= 0 && c.indexOf('Определи направление') < 0) {
  c = c.replace(slide248Old, slide248New);
  a++;
  console.log('✓ Слайд 24.8: Как думать');
}

// 6. «Когда применять» в Сборнике формул
const ykor18 = `

**Когда применять:** любые задачи с двумя парами связанных величин (больше/меньше в одной колонке — больше/меньше в другой, или наоборот).`;
const ykor19 = `

**Когда применять:** задачи, где две величины двигаются вместе (рабочие/время, скорость/путь, цена/количество).`;
const ykor20 = `

**Когда применять:** скидки, налоги, изменение цены, рост населения, наценки — везде, где в задаче есть слово «процент» или знак \\(\\%\\).`;
const ykor21 = `

**Когда применять:** карты, чертежи, модели, планы квартир — везде, где есть отношение расстояния на рисунке к реальному.`;
const ykor22 = `

**Когда применять:** банковские вклады с капитализацией, инфляция, ежегодный рост показателя, инвестиции с реинвестированием.`;

const ykorSlides = [
  ['### Слайд 18. Шпаргалка пропорции', ykor18, 'любые задачи с двумя парами'],
  ['### Слайд 19. Шпаргалка зависимостей', ykor19, 'рабочие/время, скорость/путь'],
  ['### Слайд 20. Шпаргалка процентов', ykor20, 'наценки — везде'],
  ['### Слайд 21. Шпаргалка масштаба', ykor21, 'планы квартир'],
  ['### Слайд 22. Шпаргалка сложных процентов', ykor22, 'инвестиции с реинвестированием'],
];

for (const [header, ykor, marker] of ykorSlides) {
  if (c.indexOf(header) >= 0 && c.indexOf(marker) < 0) {
    // Найдём конец слайда (следующий ### Слайд)
    const idx = c.indexOf(header);
    let end = c.indexOf('### Слайд', idx + header.length);
    if (end < 0) end = c.indexOf('## ', idx + header.length);
    if (end < 0) end = c.length;
    const slideContent = c.substring(idx, end);
    const newSlideContent = slideContent + ykor;
    c = c.substring(0, idx) + newSlideContent + c.substring(end);
    a++;
    console.log('✓ ' + header.replace('### ', ''));
  }
}

console.log('\nApplied: ' + a);
fs.writeFileSync(p, c, 'utf8');

const slides = c.match(/^### Слайд [^\n]*$/gm);
console.log('Total slides: ' + slides.length);

// Оставшиеся эмодзи
const remaining = c.match(/[\u{1F300}-\u{1FAFF}]|[\u{2600}-\u{27BF}]/gu);
if (remaining) {
  const counts = {};
  remaining.forEach(e => counts[e] = (counts[e] || 0) + 1);
  console.log('Remaining emoji:');
  Object.keys(counts).forEach(k => console.log('  ' + k + ' x' + counts[k]));
}
